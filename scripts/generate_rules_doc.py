#!/usr/bin/env python3
"""Generate docs/semgrep-rules.md from the bundled rules file (requires PyYAML, a dev dependency).

python scripts/generate_rules_doc.py          # write the file
python scripts/generate_rules_doc.py --check  # exit 1 if the committed file is stale
"""

from __future__ import annotations

import re
import sys
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parent.parent
RULES = ROOT / "src" / "reposcan" / "data" / "semgrep-rules.yml"
TARGET = ROOT / "docs" / "semgrep-rules.md"
LANG_LABEL = {
    "python": "Python",
    "javascript": "JavaScript",
    "typescript": "TypeScript",
    "go": "Go",
    "java": "Java",
}
SEVERITY = {"ERROR": "high", "WARNING": "medium", "INFO": "low"}


def render() -> str:
    rules = yaml.safe_load(RULES.read_text(encoding="utf-8"))["rules"]
    rows = []
    for rule in rules:
        cwe_text = str(rule["metadata"]["cwe"][0])
        cwe = re.match(r"CWE-\d+", cwe_text)
        languages = ", ".join(LANG_LABEL.get(lang, lang) for lang in rule["languages"])
        rows.append(
            f"| `{rule['id']}` | {languages} | {SEVERITY[rule['severity']]} | {cwe.group(0) if cwe else '-'} "
            f"| {rule['message'].replace('|', '/')} |"
        )
    return f"""# Bundled Semgrep rules

<!-- Generated by scripts/generate_rules_doc.py; do not edit by hand. -->

reposcan ships {len(rules)} original, MIT-licensed Semgrep rules in `src/reposcan/data/semgrep-rules.yml`.
They run offline (no registry access, no telemetry) and are deliberately **high-precision**: each pattern
targets a construct that is rarely legitimate, and each rule has both a vulnerable and a safe test case.
This is a baseline, not a complete SAST ruleset. Bring your own rules for real coverage:

```toml
[scanners.semgrep]
rules = ["rules/team-rules.yml"]   # relative to the reposcan config file
```

Severity mapping: Semgrep `ERROR` becomes **high**, `WARNING` becomes **medium** (see the
[user guide](user-guide.md#the-unified-finding)).

| Rule id | Languages | Severity | CWE | What it flags |
|---|---|---|---|---|
{chr(10).join(rows)}

## Testing the rules

Every rule is covered by annotated files in `tests/semgrep/` (`# ruleid: <id>` on the line before code
that must match, `# ok: <id>` before look-alike code that must not). Run the real harness:

```bash
pytest -m integration -k bundled_semgrep     # uses Semgrep's own `semgrep --test`
```

A plain unit test (no Semgrep needed) also checks that every rule has metadata and at least one positive and
one negative test case. When you add a rule, add both cases and regenerate this page with
`python scripts/generate_rules_doc.py`.
"""


def main() -> int:
    text = render()
    if "--check" in sys.argv:
        if not TARGET.exists() or TARGET.read_text(encoding="utf-8") != text:
            print("docs/semgrep-rules.md is stale; run scripts/generate_rules_doc.py", file=sys.stderr)
            return 1
        print("rules reference is up to date")
        return 0
    TARGET.write_text(text, encoding="utf-8")
    print(f"wrote {TARGET.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
